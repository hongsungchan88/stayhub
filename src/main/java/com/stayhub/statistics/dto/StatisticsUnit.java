package com.stayhub.statistics.dto;

/**
 * 통계 조회 단위 (STA-001·003 입력 "조회 기간(일/주/월)").
 *
 * <p>조회 기간(from~to)을 이 단위로 잘라 구간별 값을 돌려줍니다.
 * 주는 월요일에 시작하고, 첫 구간·마지막 구간은 조회 기간에 맞춰 잘립니다.
 * 예) 11/27(금)~12/02, WEEK → [11/27~11/29], [11/30~12/02]
 */
public enum StatisticsUnit {

	/** 하루씩 */
	DAY,

	/** 한 주씩 (월요일 시작) */
	WEEK,

	/** 한 달씩 (달력 월) */
	MONTH
}
